import { getAppBaseUrl } from "@/config/app";
import { getPlans, formatUsd } from "@/config/plans";
import { ROOM_SHORT_NAMES } from "@/config/rooms";
import { REFERENCE_CHART_COUNT } from "@/config/poker/reference-charts";

// Развёрнутая версия llms.txt (см. app/llms.txt/route.ts) — методика продукта подробнее,
// для ИИ-агентов, которым короткой сводки недостаточно.
export const dynamic = "force-dynamic";

export async function GET() {
  const base = getAppBaseUrl();
  const plans = getPlans();

  const planLines = plans
    .map((p) => {
      const limit = p.unlimited ? "без ограничений (fair-use)" : `${p.tournamentLimit} турниров/период`;
      return `- ${p.title}: ${formatUsd(p.priceUsd)}/мес, ${limit}`;
    })
    .join("\n");

  const body = `# Whygrid — подробно

## Что это
Whygrid — инструмент для турнирных игроков микролимитов (MTT), которые хотят разбирать
каждый свой турнир, а не абстрактные споты из учебника, и не готовы платить за час живого
коуча за каждый разбор.

## Как это устроено
1. Игрок загружает HH-файл (историю раздач) сыгранного турнира.
2. Детерминированный парсер разбирает файл и считает метрики: VPIP, PFR, pot odds, SPR,
   позицию, потери в фишках, тип раздачи (критическая/сильная/средняя по сложности решения).
3. AI-тренер выбирает самые спорные раздачи и заводит диалог: спрашивает, почему игрок
   сыграл именно так, — и только после ответа показывает вердикт. Прямого перехода
   «раздача → готовая оценка» без вопроса в продукте нет.
4. Открывашки (какой диапазон разумно разыгрывать с той или иной позиции) сверяются с
   открытыми эталонными чартами (${REFERENCE_CHART_COUNT} штук, ${base}/charts) — не
   солвер, а рабочая норма для онлайн-турниров микролимитов.

## Принцип: числа считает код, не ИИ
Все покерные метрики (эквити, пот-оддсы, ауты, доли банка, потери в фишках) вычисляет
парсер по правилам покера — детерминированно, один и тот же расклад всегда даёт одно и то
же число. Языковая модель эти числа не пересчитывает и не выдумывает — только объясняет их
и ведёт диалог вопросами. Если модель не уверена в стратегической оценке — она формулирует
это как уточняющий вопрос игроку, а не выдаёт категоричный совет.

## Поддерживаемые покерные румы (${ROOM_SHORT_NAMES.length})
${ROOM_SHORT_NAMES.join(", ")}

## Тарифы
${planLines}
Первый турнир любого игрока разбирается бесплатно, без привязки карты.

## Для кого это
Для регулярного игрока микролимитных турниров (MTT), который хочет разбирать именно свои
сыгранные раздачи на своих данных, а не общие примеры, и которому не подходит по цене или
времени разовая консультация с живым коучем.

## Чего в продукте нет
- Нет GTO-солвера и точных префлоп-Nash-диапазонов там, где они не выверены — там, где
  эталона нет, продукт честно об этом говорит, а не подставляет приближение как точный факт.
- Нет выдуманных отзывов, счётчиков или метрик на сайте — только то, что можно проверить.

## Ссылки
- ${base}/ — главная
- ${base}/example — настоящий разбор одной раздачи целиком, без регистрации
- ${base}/about — почему создатель сделал этот продукт
- ${base}/pricing — тарифы
- ${base}/charts — эталонные чарты
- ${base}/how-to-export — как выгрузить историю раздач по румам
`;

  return new Response(body, {
    headers: { "Content-Type": "text/plain; charset=utf-8" },
  });
}
