/**
 * Тесты pageItems (lib/pagination.ts) — какие номера страниц показывает строка
 * навигации под списком «Мои турниры».
 *
 * Покрывают:
 *  1. Мало страниц — все подряд, без многоточий.
 *  2. Много страниц — первая, последняя, текущая с соседями; разрывы схлопнуты.
 *  3. Многоточие не подменяет одну-единственную страницу (было бы шире номера).
 *  4. Края: первая и последняя страница не дают дублей и номеров вне диапазона.
 */

import { describe, it, expect } from "vitest";
import { pageItems } from "@/lib/pagination";

describe("pageItems", () => {
  it("одна страница → только она", () => {
    expect(pageItems(1, 1)).toEqual([1]);
  });

  it("мало страниц → все подряд, без многоточий", () => {
    expect(pageItems(2, 4)).toEqual([1, 2, 3, 4]);
    expect(pageItems(3, 5)).toEqual([1, 2, 3, 4, 5]);
  });

  it("середина длинного списка → многоточия с обеих сторон", () => {
    expect(pageItems(6, 12)).toEqual([1, "gap", 5, 6, 7, "gap", 12]);
  });

  it("первая страница → многоточие только справа", () => {
    expect(pageItems(1, 12)).toEqual([1, 2, "gap", 12]);
  });

  it("последняя страница → многоточие только слева", () => {
    expect(pageItems(12, 12)).toEqual([1, "gap", 11, 12]);
  });

  it("многоточие не подменяет одну страницу — рисуем номер", () => {
    // Между 1 и 3 пропущена ровно 2-я: многоточие тут заняло бы больше места,
    // чем сам номер, и спрятало бы доступный клик.
    expect(pageItems(4, 12)).toEqual([1, "gap", 3, 4, 5, "gap", 12]);
    expect(pageItems(3, 12)).toEqual([1, 2, 3, 4, "gap", 12]);
  });

  it("края не дают дублей: соседи за диапазоном отброшены", () => {
    expect(pageItems(1, 2)).toEqual([1, 2]);
    expect(pageItems(2, 2)).toEqual([1, 2]);
  });
});
