import { describe, it, expect } from "vitest";
import { sanitizeBoard } from "@/parser";

// Баг реального тестера 12.07: тренер описал борд «J-5-J-T» с апелляцией к картам, которых
// там нет. Корень (расследование): 888/iPoker склеивают борд из построличных Dealing-строк
// без дедупа/лимита → ран-ит-твайс или повтор строки раздувает борд >5 карт с дублями, и
// сырой массив уходит в промпт целиком, рассинхронясь с поуличными фактами. Санитайзер это
// чинит на выходе парсера для всех румов.
describe("sanitizeBoard — чистка борда снимка", () => {
  it("валидный борд ривера (5 карт) не трогается", () => {
    expect(sanitizeBoard(["Jc", "5h", "7d", "Th", "2s"])).toEqual(["Jc", "5h", "7d", "Th", "2s"]);
  });

  it("валидный борд тёрна (4 карты) не трогается", () => {
    expect(sanitizeBoard(["Jc", "5h", "Jd", "Th"])).toEqual(["Jc", "5h", "Jd", "Th"]);
  });

  it("ран-ит-твайс / повтор Dealing: дубли карт удаляются", () => {
    // флоп продублировался, тёрн один → должно схлопнуться в валидный борд тёрна
    expect(sanitizeBoard(["Jc", "5h", "7d", "Jc", "5h", "7d", "Th"])).toEqual(["Jc", "5h", "7d", "Th"]);
  });

  it("борд длиннее 5 обрезается до 5", () => {
    expect(sanitizeBoard(["Ac", "Kc", "Qc", "Jc", "Tc", "9c"])).toEqual(["Ac", "Kc", "Qc", "Jc", "Tc"]);
  });

  it("битые токены отсекаются", () => {
    expect(sanitizeBoard(["Jc", "XX", "5h", "10h", "7d"])).toEqual(["Jc", "5h", "7d"]);
  });

  it("пустой борд (не дошло до флопа) остаётся пустым", () => {
    expect(sanitizeBoard([])).toEqual([]);
  });
});
