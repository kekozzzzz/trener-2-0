// Раньше световое пятно жило только в первом экране и читалось как случайный блик.
// Теперь это система, проходящая через всю страницу: сетка-миллиметровка, крестики
// на её узлах и два источника света по диагонали.
//
// Слой лежит под содержимым (z-0) и не перехватывает клики. Секции поверх него не
// должны закрашивать себя непрозрачным фоном — иначе фон в них пропадёт; плотными
// остаются только карточки, им так и положено.
export function Backdrop() {
  return (
    <div aria-hidden className="backdrop">
      <div className="backdrop-grid" />
      <div className="backdrop-crosses" />
      <div className="backdrop-glow-tr" />
      <div className="backdrop-glow-bl" />
    </div>
  );
}
