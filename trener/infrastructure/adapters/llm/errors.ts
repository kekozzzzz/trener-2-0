// Брак СОДЕРЖАНИЯ ответа модели (сторожа валидатора), в отличие от сбоя связи с релеем.
// Разделение нужно повтору: причину брака содержания есть смысл показать модели на следующей
// попытке («ты не назвал порог - назови»), а таймаут релея в промпт подмешивать нельзя - это
// мусор в запросе, к тексту ответа он отношения не имеет.
//
// Откуда выросло (карантин 26.09, задача 8517cb7e): три попытки разбора были не тремя попытками,
// а одной, повторённой трижды - причина брака писалась в tasks.error и там же оставалась.
export class ContentRejectedError extends Error {
  constructor(message: string) {
    super(message);
    this.name = "ContentRejectedError";
  }
}

// Причина брака содержания из сохранённой ошибки прошлой попытки. Воркер пишет в tasks.error
// `String(err)`, поэтому узнаём по имени класса в начале строки. Вернули null - повтор идёт
// как раньше, вслепую (сбой связи, нехватка хендлера, ошибка БД).
export function contentRejectionReason(error: string | null): string | null {
  if (!error) return null;
  const m = /^ContentRejectedError:\s*(.+)$/s.exec(error.trim());
  return m ? m[1].trim() : null;
}
