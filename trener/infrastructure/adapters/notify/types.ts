// Порт уведомлений администратору (architecture/06-внешние-сервисы.md, раздел 2.2):
// «сообщи администратору о событии». За портом — сменный адаптер (правило 4):
// сейчас Telegram, запасной — email на тот же адрес, когда появится email-адаптер.
// Бизнес-логика зовёт порт и не знает, какой канал за ним стоит.
export interface NotifyPort {
  // Отправить администратору одно текстовое сообщение. Бросает при ошибке
  // доставки — решение «глушить или нет» принимает вызывающий (см. safeNotifyAdmin).
  notifyAdmin(message: string): Promise<void>;

  // Лёгкая проверка доступности канала для /api/health: getMe через релей (без
  // отправки сообщения). true — канал жив (релей + доверие серту + токен в порядке).
  // НЕ бросает: реализация сама ловит ошибку и возвращает false.
  ping(): Promise<boolean>;
}
