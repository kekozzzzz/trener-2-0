// Подмена обезличенного «Hero» на покерный ник игрока — ТОЛЬКО при показе текста
// пользователю. Вход LLM остаётся обезличенным (Hero/Player N, без никнеймов) —
// приватность (правило 5); ник в модель не передаём, заменяем уже в готовом тексте.
//
// Заменяем по границе слова, чтобы не задеть слова, где "Hero" — часть (напр. имени).
// Ник подставляем через функцию-замену, а не строку: иначе символы `$` в нике
// (`$&`, `$1`, `$$`) были бы истолкованы как спецсинтаксис замены и исказили текст.
export function personalizeHero<T extends string | null | undefined>(
  text: T,
  nickname: string | null,
): T {
  if (!text || !nickname) return text;
  return text.replace(/\bHero\b/g, () => nickname) as T;
}
