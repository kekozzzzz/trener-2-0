export type ChainVerdict = "NORM" | "BORDER" | "LEAK" | "TOO_FEW";

// Минимум наблюдений, ниже которого вердикт не выносим вовсе: на десятке случаев доля скачет от
// нуля до сотни. Показать картинку можно всегда (правило Артёма «не молчать»), но ПРИГОВОР —
// только когда данных хватает.
export const MIN_SAMPLE_FOR_VERDICT = 50;

export function chainVerdict(id: ChainId, folded: number, faced: number): ChainVerdict {
  if (faced < MIN_SAMPLE_FOR_VERDICT) return "TOO_FEW";
  const pct = (folded / faced) * 100;
  const n = CHAIN_NORMS[id];
  if (pct >= n.exploitableFrom) return "LEAK";
  if (pct > n.normHigh || pct < n.normLow) return "BORDER";
  return "NORM";
}
