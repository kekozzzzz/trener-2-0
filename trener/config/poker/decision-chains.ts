// ЦЕПОЧКИ РЕШЕНИЙ — где деньги утекают систематически, с ТОЧНОЙ ценой.
//
// Зачем именно цепочки. Артём (20.07) хотел показывать «сколько ты потерял на плохих открывашках»,
// но исследование 16.07 показало: реализованный результат на 100-1000 раздачах — ШУМ, судить по
// нему значит делать ровно то, с чем продукт борется. А EV-потерю посчитать нечем: наши чарты
// бинарные (рука в диапазоне или нет), числовых EV в них не заложено.
//
// Выход нашёл Артём: смотреть ЦЕПОЧКИ решений. «Открылся на 2 BB и сбросил на 3-бет» стоит РОВНО
// 2 BB — это арифметика, а не оценка: дисперсии нет, работает с первой раздачи. Так деньги
// становятся честным числом.
//
// ⚠️ГЛАВНОЕ ПРАВИЛО: отданные фишки — ЕЩЁ НЕ УТЕЧКА. Сбросить после промаха по флопу — нормальный
// покер, так играют все. Голая сумма «отдано 552 BB» прочитается как катастрофа при совершенно
// здоровой игре. Поэтому цепочка ВСЕГДА показывается со ЗНАМЕНАТЕЛЕМ и НОРМОЙ, а вердикт имеет
// три состояния: в норме / на границе / за нормой. Деньги называем ТОЛЬКО в последнем случае.
// Это прямое следствие правила Артёма от 16.07: «никогда не показывать число без ШКАЛЫ».
//
// ⚠️Второе правило: инструмент обязан уметь сказать «я проверил, у тебя тут порядок». Молчание
// неотличимо от «не смотрел», а доверие строится на том, что игрока не пугают выдуманной проблемой.
//
// НОРМЫ — из внешних источников, не выдуманы:
//  • Фолд на 3-бет: сбалансированная частота ≈55%, защищать опен-диапазон стоит 40-55% времени;
//    65%+ — «отдаёшь слишком легко, против тебя печатают деньги» (pokerstrategy.com, PokerStars
//    Learn, SplitSuit). Берём норму 45-60%, за нормой — от 65%.
//  • Фолд на ставку флопа: меньше 50% — коллируешь слишком много; больше 70% — тебя легко
//    эксплуатировать бесконечными контбетами (mypokercoaching.com, pokercopilot.com).
//    Берём норму 50-65%, за нормой — от 70%.
// Пороги — бизнес-настройка (правило 3), правятся здесь одной строкой.

export type ChainId = "FOLD_TO_3BET" | "FOLD_FLOP_BET" | "FOLD_TURN_BET";

export type ChainNorm = {
  id: ChainId;
  /** Человеческое имя цепочки для показа. */
  title: string;
  /** Что считаем знаменателем — чтобы игрок понимал, из чего доля. */
  denominator: string;
  /** Нижняя и верхняя границы НОРМЫ (доля в процентах). */
  normLow: number;
  normHigh: number;
  /** С этой доли поведение становится эксплуатируемым — тут и называем деньги. */
  exploitableFrom: number;
  /** Откуда норма — чтобы через полгода не гадать. */
  source: string;
};

