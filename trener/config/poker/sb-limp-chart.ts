// Чарт ЛИМПА С МАЛОГО БЛАЙНДА: чем входим лимпом при фолде до нас и что делаем, когда большой
// блайнд поднимает. Заказ Артёма 19.07: «по SB нам надо ещё лимп-колл, лимп-пасс, лимп-рейз».
//
// СТРУКТУРА (решение Артёма 19.07, вариант «лимп = только слабые»): рейз-чарт SB НЕ трогаем —
// все карманные пары и сильные руки по-прежнему открываются рейзом (rfi-chart, SB ~37%). Значит
// лимп-пул по определению СЛАБЫЙ: ловушки сильной рукой в нём нет по построению. Чарт судит ровно
// две ветки — ЛИМП-КОЛЛ и ЛИМП-ФОЛД (что делаем, когда BB поднял наш лимп).
//
// Почему лимп вообще есть: по эталону продукта слабые руки с малого блайнда ЛИМПЯТ, а не фолдят —
// полблайнда уже вложено, цена входа мала, а против одного BB дешёвый флоп окупается (см. правило
// в preflop-chart-fact: «SB-лимп не утечка»). Этот чарт лишь доводит мысль до конца: раз лимпим,
// надо знать, что делать на рейз.
//
// ТАКТИКА ЦЕЛИКОМ (со слов Артёма 19.07, это его рабочая схема, а не выкладка из книги):
// входим лимпом ~100% рук → если BB чекнул, на флопе ставим ОДИН БЛАЙНД «на проверку» → не прошло
// или совсем не попали — сдаёмся сразу, потеряв копейку. Забираем блайнды с анте достаточно часто,
// чтобы схема окупалась, а проигрыш ограничен размером стаба. Ставка в один блайнд по флопу —
// БАЗОВАЯ линия ПРОТИВ ЛЮБОГО соперника, её оговаривать по типу оппонента не нужно.
//
// ⚠️ЛИМП-РЕЙЗ МУСОРОМ работает ТОЛЬКО ПРОТИВ РЕГУЛЯРОВ (уточнение Артёма): они понимают, что лимпом
// идут дёшево посмотреть флоп, и атакуют лимп широко — по такому рейзу переставиться блефом
// прибыльно. Против пассивной станции бессмысленно. В ЧАРТ это не зашито, см. SB_LIMP_RAISE_HINT.
//
// ⚠️Данные — рабочая позиция продукта, а не единственная истина (см. оговорку на /charts).
// Правило 3: диапазоны в конфиге. Правило 1: попадание руки в диапазон считает код.

import { buildRange } from "./hand-range";
import { rfiCellState } from "./rfi-chart";

// ⚠️ЛИМП-РЕЙЗА В ЧАРТЕ НЕТ — сознательно (решение Артёма 19.07: «оставь просто текстовую подсказку,
// это не будет как эталон, это очень ситуативная история»). Он не свойство РУКИ, а решение по
// ЧТЕНИЮ соперника: против рега, который широко атакует лимпы, переставиться блефом прибыльно
// почти любой рукой, а против пассивного — не нужно вовсе. Зашивать такое в диапазон значит выдать
// ситуативный приём за норму, по которой тренер начнёт судить. Подсказка живёт текстом: константа
// SB_LIMP_RAISE_HINT ниже, её отдаёт вердикт чарта.
export const SB_LIMP_RAISE_HINT =
  "Лимп-рейз в эталон НЕ входит: это ситуативный приём по чтению соперника, а не диапазон рук. " +
  "Против РЕГУЛЯРА, который широко атакует лимпы (в том числе мусором), переставиться блефом " +
  "бывает прибыльно почти любой рукой — фолд-эквити есть. Против пассивного/коллирующего лимп-рейз " +
  "блефом бессмысленен. Поэтому НЕ называй отсутствие лимп-рейза ошибкой и не требуй его — упомянуть " +
  "можно только если игрок сам описал соперника как агрессивного атакующего лимпы.";

// ЛИМП-КОЛЛ. Ширина задана НАБЛЮДЕНИЕМ АРТЁМА (19.07), а не общей теорией: непассивные соперники
// понимают, что лимпом идут дёшево посмотреть флоп, и рейзят по лимпу МУСОРОМ. Против такого
// широкого рейз-диапазона колл идёт не только по играбельности, но и по голой силе на вскрытии:
// туз или король высокой картой уже бьёт его блеф. Поэтому сюда добавлены разномастные тузы,
// короли и бродвеи — против честного рейз-диапазона их бы тут не было.
const SB_LIMP_CALL = [
  // любая масть, что не ушла в рейз, — дешёвый флоп с потенциалом
  "Q2s+", "J2s+", "T2s+", "92s+", "82s+", "72s+", "62s+", "52s+", "42s+", "32s",
  // разномастные связки и однозазорные — играют стриты
  "T9o", "98o", "87o", "76o", "65o", "J8o", "T8o", "97o", "86o", "75o",
  // высокая карта против широкого рейза — бьёт его мусор на вскрытии
  "A4o", "A3o", "A2o", "K4o", "K3o", "K2o",
  "Q8o", "Q7o", "Q6o", "Q5o", "Q4o", "Q3o", "Q2o",
  "J7o", "J6o", "J5o", "J4o", "J3o", "J2o",
  "T7o", "T6o", "T5o", "T4o", "T3o", "T2o",
];

// ЛИМП-ФОЛД — вошли дёшево, но на рейз сбрасываем без сожаления: ни высокой карты, ни связи.
// Остаётся только низ без масти. Тактика тут не «выиграть до флопа», а посмотреть флоп за копейку
// (см. заметку про ставку в один блайнд на проверку в шапке файла).
const SB_LIMP_FOLD = [
  "96o", "95o", "94o", "93o", "92o",
  "85o", "84o", "83o", "82o",
  "74o", "73o", "72o",
  "64o", "63o", "62o",
  "54o", "53o", "52o",
  "43o", "42o", "32o",
];

const LIMP_CALL_SET = buildRange(SB_LIMP_CALL);
const LIMP_FOLD_SET = buildRange(SB_LIMP_FOLD);

export type SbLimpCellState =
  | "RAISE_FIRST" // этой рукой открываем РЕЙЗОМ — лимп тут не наш выбор
  | "LIMP_CALL" // лимпим и платим рейз BB
  | "LIMP_FOLD" // лимпим, но на рейз BB сбрасываем
  | "FOLD"; // не входим вовсе

// Что делать с рукой на малом блайнде при фолде до нас. Порядок проверок важен: рейз-чарт главнее
// — он источник правды по открытию, и лимп-чарт его не переопределяет.
export function sbLimpCellState(code: string): SbLimpCellState {
  const rfi = rfiCellState("SB", code);
  if (rfi === "ALWAYS" || rfi === "SOMETIMES") return "RAISE_FIRST";
  if (LIMP_CALL_SET.has(code)) return "LIMP_CALL";
  if (LIMP_FOLD_SET.has(code)) return "LIMP_FOLD";
  return "FOLD";
}
