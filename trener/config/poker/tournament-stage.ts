// ПРИЗНАКИ ПОЗДНЕЙ СТАДИИ ТУРНИРА — чтобы тренер СПРОСИЛ игрока, а не выдумал стадию.
//
// Проблема: HH-файл стадию не показывает. Сколько игроков осталось в турнире, близко ли деньги,
// финальный ли стол — этого в файле нет, и продукт принципиально таких чисел не сочиняет (см. факт
// «Зона стека»: «стадию турнира HH НЕ показывает — её не выдумывай»). А стадия решает многое:
// у призовых и на пузыре те же руки играются иначе.
//
// Идея Артёма (20.07): «давай будем спрашивать — если стол 3-макс или 4-макс и уровни большие,
// то можно и спросить». Здесь поэтому НЕ вывод о стадии, а ТРИГГЕР ВОПРОСА.
//
// ⚠️КАК ВЫБРАНЫ ПОРОГИ. Артём дал ориентиры из практики: «примерно на уровне 15 это около бабло;
// на уровне 20 уже может быть и финальный, и предфинальный стол». Но проверка по внешним источникам
// (CardsChat, Upswing, PokerNews, GTO Wizard) показала, что стадию определяют РАЗМЕРЫ СТЕКОВ
// относительно блайндов и близость выплат, а НЕ номер уровня: уровень 15 в турбо и в глубоком
// турнире — разные вещи. Поэтому:
//   • основной признак — СРЕДНИЙ СТЕК ЗА СТОЛОМ В БОЛЬШИХ БЛАЙНДАХ. Он структурно-независим:
//     фишек в турнире фиксированное количество, а блайнды растут, поэтому средний стек в BB
//     неизбежно падает по ходу любого турнира;
//   • номер уровня — вспомогательный, работает как калибровка под турниры Артёма;
//   • короткий стол — самостоятельный признак: столы схлопываются по мере вылетов.
//
// Калибровка по 2739 раздачам Артёма (средний стек за столом по группам уровней):
//   уровни 1-5 → 121.5 BB, 6-10 → 65.7, 11-14 → 44.6, 15-19 → 34.6, 20-24 → 27.0, 25+ → 29.4.
// Отсюда пороги в BB: его «уровень 15» ≈ 35 BB, «уровень 20» ≈ 27 BB.
//
// Правило 3: пороги — бизнес-настройка, живут в конфиге и правятся одной строкой.

// Ориентиры Артёма по номеру уровня (калибровка под его турниры, структурно-зависимы).
export const LEVEL_NEAR_MONEY = 15;
export const LEVEL_FINAL_TABLE = 20;

// Средний стек за столом в BB — структурно-независимый признак прогресса турнира.
export const AVG_STACK_NEAR_MONEY_BB = 35;
export const AVG_STACK_FINAL_TABLE_BB = 27;

// Короткий стол: в турнире столы схлопываются по мере вылетов, 3-4 игрока — почти всегда конец.
export const SHORT_TABLE_SEATS = 4;

export type StageHint = "NEAR_MONEY" | "FINAL_TABLE" | null;

// Признак поздней стадии. null — признаков нет, молчим (в сомнении не спрашиваем, чтобы не сыпать
// вопросами на ранней дистанции). Любой из признаков достаточен: это лишь повод СПРОСИТЬ.
export function stageHint(
  level: number | null | undefined,
  seatCount: number,
  avgStackBb: number | null,
): StageHint {
  if (seatCount > 0 && seatCount <= SHORT_TABLE_SEATS) return "FINAL_TABLE";
  if (level != null && level >= LEVEL_FINAL_TABLE) return "FINAL_TABLE";
  if (avgStackBb != null && avgStackBb > 0 && avgStackBb <= AVG_STACK_FINAL_TABLE_BB) return "FINAL_TABLE";
  if (level != null && level >= LEVEL_NEAR_MONEY) return "NEAR_MONEY";
  if (avgStackBb != null && avgStackBb > 0 && avgStackBb <= AVG_STACK_NEAR_MONEY_BB) return "NEAR_MONEY";
  return null;
}
