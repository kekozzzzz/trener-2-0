// Премиум-руки, которыми префлоп-олл-ин — это ФОРС, а не решение: проигранный префлоп-олл-ин
// такой рукой уходит в тихую стопку (кулер), а не в «Стоит обсудить» (Артём 18.07: «туз-король,
// кулер, что бы ни случилось я выставляюсь» — разбирать там нечего, вердикт получается пустой
// «продолжай по математике»). ВАЖНО: отсечка работает ТОЛЬКО на префлоп-олл-инах без постфлоп-
// решений. Постфлоп с теми же руками — где в тебя летят рейзы на тёрне/ривере и надо было сдаться
// под сет/две пары/готовый стрит-флеш, а ты «не почувствовал руку» — остаётся в разборе.
//
// Порог — бизнес-настройка (правило 3), живёт здесь, а не в коде классификатора. Тюнится одной
// строкой: `TT+` = карманные пары от десяток и выше; большие тузы AK/AQs — стандартный get-it-in
// префлопом на этих стеках. Ниже (99, AJ, KQ) коллы становятся спот-зависимыми — их разбираем.
export const FORCED_PREFLOP_ALLIN_TOKENS = ["TT+", "AKs", "AKo", "AQs"];

export const FORCED_PREFLOP_ALLIN_RANGE = buildRange(FORCED_PREFLOP_ALLIN_TOKENS);
