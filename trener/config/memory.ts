// Параметры памяти тренера — поиска похожих прошлых раздач игрока (features/memory).
// Правило 3: бизнес-настройки в конфиге, не в логике. Значения 2026-07-05 — по запросу
// Артёма окно расширено с 200 раздач до последних 100 турниров, чтобы память реально
// срабатывала в первые же недели игры.

// Сколько ПОСЛЕДНИХ турниров игрока сканируем в поиске похожих раздач.
export const MEMORY_SCAN_TOURNAMENTS = 100;

// Страховочный потолок лёгкой выборки (id + отпечаток): даже при очень длинных
// турнирах запрос не разрастается бесконтрольно.
export const MEMORY_SCAN_HANDS_MAX = 25000;

// Порог похожести по отпечатку: из 6 признаков ≥5 совпавших — «похоже», 6 — «один в один».
// Меньше — натянуто, такой канал не показываем (канал «та же ошибка» порога не требует —
// там совпадение метки детектора само по себе содержательно).
export const MEMORY_MIN_MATCH_SCORE = 5;

// Не заваливаем промпт: максимум прошлых раздач в блоке памяти.
export const MEMORY_MAX_PRIOR_SPOTS = 3;

// Длина напоминания вердикта прошлого разбора в блоке памяти (символов, режем по слову).
export const MEMORY_VERDICT_SNIPPET = 300;
