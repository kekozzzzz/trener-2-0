// Хвост промпта для ЗРЯЧЕГО повтора: что именно забраковала проверка в прошлой попытке.
//
// Откуда выросло (карантин 26.09, задача 8517cb7e): повтор шёл тем же запросом и не знал
// причины отказа, поэтому три попытки давали один и тот же брак - это была не тройная попытка,
// а одна, повторённая трижды. Причина у нас есть всегда (её пишет сторож), показать её дёшево.
//
// Правило 3: текст живёт в config/prompts, а не в адаптере.

// Предел длины причины: в неё попадает цитата из прошлого ответа модели («назвал карту вне
// снимка: «Kh»»), и раздувать ею запрос незачем.
const MAX_REASON_LEN = 300;

export function withRejectionNote(prompt: string, reason?: string): string {
  const clean = reason?.trim();
  if (!clean) return prompt;
  const short = clean.length > MAX_REASON_LEN ? `${clean.slice(0, MAX_REASON_LEN)}…` : clean;
  return `${prompt}

## Прошлая попытка забракована

Автоматическая проверка отклонила твой прошлый ответ по этой же задаче:
«${short}»

Исправь ИМЕННО это нарушение. Остальное переписывать ради изменения не нужно - правила и факты
те же, что выше. Если правило требует назвать число, бери его из фактов парсера, не считай сам.`;
}
