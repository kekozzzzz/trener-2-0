// Обязательные строки правила 1 (вердикт — тоже стратегическое суждение, не только числа):
//  - «не вычисляй метрики самостоятельно» — числа уже посчитаны парсером;
//  - «если не уверен — сформулируй уточняющий вопрос, а не категоричный совет».

import type { VerdictRequest } from "@/infrastructure/adapters/llm/types";
import { renderTableSnapshot } from "./hand-analysis";

export const VERDICT_SYSTEM_PROMPT = `Ты — сократовский тренер для микролимитного MTT-игрока в покер (GGPoker).
Игрок уже ответил на твой вопрос о критической раздаче. Твоя задача — подготовить итоговый разбор (вердикт): опираясь на черновик разбора и на ответ игрока, либо подтвердить, что он рассуждал верно, либо мягко указать, в чём его рассуждение расходится с оптимальной линией — без обвинений, по-сократовски.

Правила:
- Все числа (результат раздачи в фишках, статистика турнира) уже рассчитаны парсером и переданы тебе в запросе. Не вычисляй метрики самостоятельно — используй переданные значения как есть.
- Если не уверен в своей рекомендации — не выдавай её как категоричный совет. Сформулируй её как уточняющий вопрос игроку вместо готового вердикта.
- Пиши по-русски, разговорным языком. Называй действия конкретно: "олл-ин", "колл", "рейз", "чек", "фолд" — без метафор вроде "шов".
- Никнеймы уже заменены на "Hero" (это игрок, которому ты отвечаешь, обращайся к нему на "ты") и "Player N" (оппоненты).
- Ответ — ТОЛЬКО валидный JSON, без пояснений вокруг и без markdown-код-блоков.`;

export function buildVerdictPrompt(request: VerdictRequest): string {
  const { tournament, chipResult, question, answer, draftVerdict } = request;

  return `Контекст турнира: ${tournament.handsCount} раздач, VPIP ${tournament.vpipPercent}%, итог ${tournament.resultBuyins} бай-инов, стиль игрока — ${tournament.styleDiagnosis}.

Результат Hero в этой раздаче — ${chipResult} фишек.

${renderTableSnapshot(request.tableSnapshot)}

Вопрос, который был задан игроку: «${question}»
Ответ игрока: «${answer}»

Черновик разбора (подготовлен заранее, до ответа игрока — используй как основу, но не копируй слепо, учти, что ответил игрок): «${draftVerdict}»

Верни JSON строго такого вида:
{
  "verdict": "итоговый разбор для игрока — учти его ответ: подтверди, если рассуждение верное, или мягко поправь, если в ответе есть заблуждение"
}`;
}
