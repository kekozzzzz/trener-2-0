// Промпт для GENERATE_TOURNAMENT_SUMMARY — продуктовый контент
// (architecture/00-правила-проекта.md, «Спроси разрешения» №5).
//
// Правило 1: все числа уже посчитаны парсером и переданы в разборах раздач —
// LLM не вычисляет метрики, только собирает общую картину из готовых данных.

import type { TournamentSummaryRequest } from "@/infrastructure/adapters/llm/types";

export const TOURNAMENT_SUMMARY_SYSTEM_PROMPT = `Ты — сократовский тренер для микролимитного MTT-игрока в покер (GGPoker).
Твоя задача — дать игроку общую картину сыгранного турнира: как он играл в целом и какие моменты стоит пересмотреть.

Правила:
- Все числа (VPIP, итог в бай-инах, результаты раздач в фишках, уровень важности) уже рассчитаны парсером и переданы тебе. Не вычисляй метрики самостоятельно.
- Опирайся ТОЛЬКО на переданные разборы раздач — не придумывай раздачи и события, которых нет в данных.
- Пиши по-русски, разговорно, обращайся к игроку на "ты". Называй действия конкретно ("олл-ин", "колл", "рейз", "чек", "фолд"), без метафор.
- "overview" — 2–4 предложения: общий стиль игры и итог, на чём в основном терял или выигрывал. Без перечисления каждой раздачи.
- "moments" — самые показательные раздачи из переданных (от 2 до 5). На каждую — короткая подпись в одну строку (что произошло). Ссылайся на раздачу её числовым полем "index" из запроса, ничего не выдумывая.
- Ответ — ТОЛЬКО валидный JSON, без пояснений вокруг и без markdown-код-блоков.`;

export function buildTournamentSummaryPrompt(request: TournamentSummaryRequest): string {
  const { tournament, hands } = request;

  const handLines = hands
    .map((h) => {
      const parts = [
        `index ${h.index}: важность ${h.importanceLevel}, результат ${h.chipResult} фишек`,
        `  сыграл: ${h.played}`,
        `  оптимально: ${h.optimal}`,
      ];
      if (h.note) parts.push(`  заметка: ${h.note}`);
      if (h.verdict) parts.push(`  вердикт: ${h.verdict}`);
      return parts.join("\n");
    })
    .join("\n\n");

  return `Метрики турнира: ${tournament.handsCount} раздач, VPIP ${tournament.vpipPercent}%, итог ${tournament.resultBuyins} бай-инов, стиль игрока — ${tournament.styleDiagnosis}.

Разобранные раздачи карточки:
${handLines}

Верни JSON строго такого вида:
{
  "overview": "2–4 предложения про общую картину турнира",
  "moments": [
    { "hand": <index раздачи из списка выше>, "label": "короткая подпись, что произошло" }
  ]
}`;
}
