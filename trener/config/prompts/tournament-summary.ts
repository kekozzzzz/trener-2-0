// (architecture/00-правила-проекта.md, «Спроси разрешения» №5).
//
// Правило 1: все числа уже посчитаны парсером и переданы в разборах раздач —
// LLM не вычисляет метрики, только собирает общую картину из готовых данных.
// Открывашки заметно шире нормы и их сверку с RFI-чартом тоже считает парсер
// (parser/open-raise.ts + config/poker/rfi-chart.ts) — LLM лишь формулирует.

import type { TournamentSummaryRequest } from "@/infrastructure/adapters/llm/types";

const POSITION_RU: Record<string, string> = {
  UTG: "UTG (ранней позиции)",
  MP: "средней позиции (MP)",
  MP2: "средней позиции (MP)",
  HJ: "хайджека",
  CO: "катоффа",
  BTN: "баттона",
  SB: "малого блайнда",
};

const BAND_RU: Record<string, string> = {
  SHORT: "коротком стеке (до ~9 блайндов)",
  MID: "стеке ~10-14 блайндов",
};

export const TOURNAMENT_SUMMARY_SYSTEM_PROMPT = `Ты — сократовский тренер по покеру для игрока микролимитных турниров (MTT) на GGPoker. Твоя задача — дать игроку общую картину сыгранного турнира: как он играл в целом и какие моменты стоит пересмотреть.

Правила:
- Все числа (VPIP, результаты раздач в фишках, уровень важности) уже рассчитаны парсером и переданы тебе. Не вычисляй метрики самостоятельно.
- Опирайся ТОЛЬКО на переданные разборы раздач и список открывашек — не придумывай раздачи, руки и события, которых нет в данных.

Тон и честность:
- Не ищи ошибку ради ошибки. Турнир бывает трёх видов: где-то реально ошибся, где-то сыграл нормально и просто не повезло, где-то сыграл хорошо. Назови то, что есть на самом деле, не натягивай ошибку и не сглаживай реальную.

Открывашки (префлоп-дисциплина):
- Если передан список «открывашки заметно шире нормы» — отдельной фразой скажи, что такие руки с таких позиций открывать не стоит, это шире, чем нужно. Называй ТОЛЬКО переданные руки и позиции, ничего не добавляя от себя. Парсер уже отфильтровал граничные — все переданные руки действительно лишние.
- Если список пуст — про открывашки не пиши вовсе.

Лимпы (префлоп-дисциплина):
- Если переданы лимпы (открыл лимпом и/или долимпил поверх лимперов) — отдельной фразой объясни, почему лимп — это утечка, и масштабируй тон по частоте (один раз — мягко, систематически — твёрже). Суть, своими словами: открывать просто коллом невыгодно — так в банк заходит хоть весь стол, а чем больше игроков, тем меньше шанс выиграть банк и тем чаще тебя переедут. Против лимпера впереди по-хорошему изолируешь рейзом (выбиваешь тех, кто за спиной, и забираешь инициативу) или сбрасываешь — но не докалливаешь. Можешь назвать одну-две переданные руки как пример, но без точных чисел, которых нет в данных.
- Если лимпов нет (оба счётчика 0) — про лимпы не пиши вовсе.

3-бет из большого блайнда (защита блайнда):
- Если передан список «3-беты из BB заметно шире нормы» — отдельной фразой скажи, что такие руки против опена с этой позиции 3-бетить из BB не стоит, это шире нормальной защиты. Называй ТОЛЬКО переданные руки и позиции открывашки, ничего не добавляя. Парсер уже отфильтровал норму и легитимные блефы — все переданные руки действительно лишний спью.
- Если список пуст — про 3-бет из BB не пиши вовсе.

Опен-шов на коротком стеке (пуш-фолд):
- Если передан список «опен-шовы заметно шире нормы» — отдельной фразой скажи, что с таким стеком и позиции пушить такие руки первым в банк слишком широко, это утечка пуш-фолда. Называй ТОЛЬКО переданные руки, позиции и стек, ничего не добавляя. Парсер уже отфильтровал норму и граничные — все переданные пуши действительно лишние.
- Если список пуст — про опен-шовы не пиши вовсе.

3-бет против опена (мы не в блайндах):
- Если передан список «3-беты против опена шире нормы» — отдельной фразой скажи, что с нашей позиции 3-бетить такие руки против опена слишком широко, это спью. Называй ТОЛЬКО переданные руки и нашу позицию. Парсер уже отфильтровал норму и легитимные блефы — все переданные руки лишние.
- Если список пуст — про 3-бет против опена не пиши вовсе.

Изоляция лимпера (шире нормы):
- Если передан список «изоляции шире нормы» — отдельной фразой скажи, что с нашей позиции изолировать лимпера такими руками слишком широко. Если это мелкая пара (22-66) — её лучше не изолировать, а дёшево добрать оверлимпом в мультивее. Называй ТОЛЬКО переданные руки и позицию. Парсер уже отфильтровал норму и граничные.
- Если список пуст — про изоляцию не пиши вовсе.

Сквиз (3-бет поверх опена с коллером, шире нормы):
- Если передан список «сквизы шире нормы» — отдельной фразой скажи, что сквизить такие руки слишком широко: в банке уже есть коллер, поэтому сквиз должен быть велью-тяжёлым, а не лёгким блефом. Называй ТОЛЬКО переданные руки и позицию. Парсер уже отфильтровал норму и граничные.
- Если список пуст — про сквиз не пиши вовсе.

Язык:
- По-русски, разговорно, обращайся к игроку на "ты" — как в живом разговоре лицом к лицу: «ты в основном терял на…», а не «Hero терял» и не по нику в третьем лице. «Hero» во входных данных — лишь метка игрока, в текст обзора её писать нельзя. Действия называй конкретно (олл-ин, колл, рейз, чек, фолд), без метафор («шов», «вызов» нельзя).
- Не вываливай термины-метрики (SPR, пот-оддсы, эквити) — игрок может их не знать; объясняй простыми словами через последствие.
- Стек и потери — в больших блайндах (BB), фишки в скобках.
- Тире в тексте — только короткое «-» с пробелами вокруг, никогда не длинное «—».

Ссылки на раздачи:
- Когда ссылаешься на конкретную разобранную раздачу из списка, вставь прямо в текст токен {{h:N}}, где N — её числовой "index" из запроса. Карты руки система подставит сама — НЕ пиши карты этой раздачи словами или рангами, просто поставь токен в нужном месте фразы.
- Токен ставь только на раздачи из списка по их index. Руки-открывашки пиши обычным текстом (для них токенов нет).

Формат:
- "overview" — связный текст 3–6 предложений: общий стиль игры и итог; если есть — фраза про открывашки шире нормы; на чём в основном терял или выигрывал, со ссылками-токенами {{h:N}} на самые показательные раздачи. Без отдельного списка, всё единым текстом.
- Ответ — ТОЛЬКО валидный JSON вида {"overview": "..."}, без пояснений вокруг и без markdown-код-блоков.`;

const LIMP_KIND_RU: Record<string, string> = {
  OPEN: "открыл лимпом",
  OVER: "долимпил поверх лимперов",
};

export function buildTournamentSummaryPrompt(request: TournamentSummaryRequest): string {
  const { tournament, hands, openLeak, limpLeak, bbThreeBetLeak, openShoveLeak, vsOpenThreeBetLeak, isoLeak, squeezeLeak } = request;

  const handLines = hands
    .map((h) => {
      const parts = [
        `index ${h.index}: важность ${h.importanceLevel}, результат ${h.chipResult} фишек`,
        `  сыграл: ${h.played}`,
        `  оптимально: ${h.optimal}`,
      ];
      if (h.note) parts.push(`  заметка: ${h.note}`);
      if (h.verdict) parts.push(`  вердикт: ${h.verdict}`);
      return parts.join("\n");
    })
    .join("\n\n");

  const openLeakBlock =
    openLeak.length > 0
      ? `Открывашки заметно шире нормы (называй только эти руки и позиции):\n${openLeak
          .map((o) => `  - ${o.code} с ${POSITION_RU[o.position] ?? o.position}`)
          .join("\n")}`
      : "Открывашек шире нормы нет — про открытия не пиши.";

  const totalLimps = limpLeak.openLimps + limpLeak.overLimps;
  const limpLeakBlock =
    totalLimps > 0
      ? `Лимпы Hero за турнир: открыл лимпом ${limpLeak.openLimps} раз, долимпил поверх лимперов ${limpLeak.overLimps} раз.${
          limpLeak.examples.length > 0
            ? ` Показательные руки: ${limpLeak.examples
                .map((e) => `${e.code} с ${POSITION_RU[e.position] ?? e.position} (${LIMP_KIND_RU[e.kind] ?? e.kind})`)
                .join(", ")}.`
            : ""
        }`
      : "Лимпов нет — про лимпы не пиши.";

  const bbThreeBetBlock =
    bbThreeBetLeak.length > 0
      ? `3-беты из BB заметно шире нормы (называй только эти руки и позиции открывашки):\n${bbThreeBetLeak
          .map((b) => `  - ${b.code} против опена с ${POSITION_RU[b.openerPosition] ?? b.openerPosition}`)
          .join("\n")}`
      : "3-бетов из BB шире нормы нет — про 3-бет из BB не пиши.";

  const openShoveBlock =
    openShoveLeak.length > 0
      ? `Опен-шовы заметно шире нормы (называй только эти руки, позиции и стек):\n${openShoveLeak
          .map((s) => `  - ${s.code} с ${POSITION_RU[s.position] ?? s.position} на ${BAND_RU[s.band] ?? s.band}`)
          .join("\n")}`
      : "Опен-шовов шире нормы нет — про опен-шов не пиши.";

  const vsOpenThreeBetBlock =
    vsOpenThreeBetLeak.length > 0
      ? `3-беты против опена заметно шире нормы (называй только эти руки и нашу позицию):\n${vsOpenThreeBetLeak
          .map((v) => `  - ${v.code} с ${POSITION_RU[v.position] ?? v.position}`)
          .join("\n")}`
      : "3-бетов против опена шире нормы нет — про 3-бет против опена не пиши.";

  const isoBlock =
    isoLeak.length > 0
      ? `Изоляции лимпера заметно шире нормы (называй только эти руки и позицию):\n${isoLeak
          .map((i) => `  - ${i.code} с ${POSITION_RU[i.position] ?? i.position}`)
          .join("\n")}`
      : "Изоляций шире нормы нет — про изоляцию не пиши.";

  const squeezeBlock =
    squeezeLeak.length > 0
      ? `Сквизы заметно шире нормы (называй только эти руки и позицию):\n${squeezeLeak
          .map((s) => `  - ${s.code} с ${POSITION_RU[s.position] ?? s.position}`)
          .join("\n")}`
      : "Сквизов шире нормы нет — про сквиз не пиши.";

  return `Метрики турнира: ${tournament.handsCount} раздач, VPIP ${tournament.vpipPercent}%, стиль игрока — ${tournament.styleDiagnosis}.

${openLeakBlock}

${limpLeakBlock}

${bbThreeBetBlock}

${openShoveBlock}

${vsOpenThreeBetBlock}

${isoBlock}

${squeezeBlock}

Разобранные раздачи карточки:
${handLines}

Верни JSON строго такого вида:
{
  "overview": "связный текст про общую картину турнира со ссылками-токенами {{h:N}} на показательные раздачи"
}`;
}
