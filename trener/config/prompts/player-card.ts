import type { PlayerCard, PlayerCardLeak } from "@/infrastructure/adapters/llm/types";
import { SELF_LEVEL_PROMPT_LABEL } from "@/config/self-level";

// Блок «Твой ученик» — память тренера об игроке для промптов всех ролей (разбор,
// диалог, вердикт, чат). Правило 1: характеристика сформулирована отдельным шагом
// на числах парсера, лики посчитал лик-трекер — здесь только рендер и правила
// пользования. План: plans/2026-07-06-память-тренера-об-игроке.md (фаза 1).
export function renderPlayerCard(card: PlayerCard | null | undefined): string {
  if (!card) return "";

  const parts: string[] = [];

  if (card.characteristic) {
    parts.push(`Сводная характеристика его игры (по ${card.tournamentsCounted} загруженным турнирам): «${card.characteristic}»`);
  }

  // Цепочки решений за всё время — готовая строка из features/profile/decision-chains.ts.
  // Внутри уже сказано, что деньги называются только при вердикте «за нормой», а при норме
  // проблему выдумывать нельзя.
  if (card.decisionChains) parts.push(card.decisionChains);

  if (card.notes.length > 0) {
    const noteLines = card.notes.map((n) => `- ${formatNoteDate(n.date)}: ${n.text}`);
    parts.push(`Твои заметки с прошлых занятий с ним (даты реальные — на них можно ссылаться):\n${noteLines.join("\n")}`);
  }

  if (card.leaks.length > 0) {
    const lines = card.leaks.map((l) => {
      const progress = l.improvedLastDay ? " — в последний игровой день ни разу (прогресс)" : "";
      return `- ${l.label}: ${l.priorTotal} раз за ${l.daysWithLeak} из ${l.windowDays} последних игровых дней${progress}`;
    });
    parts.push(`Его системные ошибки за последние игровые дни (нашли детекторы парсера, это повторяющиеся паттерны, а не разовые случаи):\n${lines.join("\n")}`);
  }

  // «Ориентир» — самооценка уровня игроком (план 2026-07-10). Мягкий приор ТОЛЬКО для
  // тона и глубины объяснений: заполнен лишь на первые турниры (окно посчитал код).
  // Прямо помечаем как «его слова, не факт», требуем верить рукам и не пропускать «почему».
  const selfLevelBlock = card.selfLevel
    ? `С КЕМ ТЫ ГОВОРИШЬ (со слов самого игрока — это его самооценка, не проверенный факт). Игрок оценил своё понимание покера так: «${SELF_LEVEL_PROMPT_LABEL[card.selfLevel]}». Подстрой под это ГЛУБИНУ и ТОН объяснений: новичку разжёвывай понятия с нуля, «глубоко в теории» — говори на языке диапазонов и не трать время на азы. Но это лишь начальная гипотеза на первые занятия: если по его рукам, ликам и разбору видно другое — верь тому, что видишь, а не этой отметке. И это НЕ повод пропускать вопрос «почему» или сокращать разбор.`
    : "";

  // Холодный старт: реальной памяти (характеристика/заметки/лики) ещё нет — идёт только
  // ориентир (или пусто, если он не задан/уже погас).
  if (parts.length === 0) return selfLevelBlock;

  const memory = `ТВОЙ УЧЕНИК — что ты знаешь о нём по всей его истории (память тренера, все числа посчитаны парсером):
${parts.join("\n\n")}

Как этим пользоваться. Ты ведёшь этого игрока давно — говори как тренер, который помнит ученика, а не знакомится заново. Если текущая раздача попадает в тему заметки из дневника — напомни договорённость с датой («мы разбирали это 28.06 — договаривались фолдить такие коллы»); заметки недавние, код уже отрезал всё старше трёх месяцев. Если решение в текущей раздаче — то же самое, что системная ошибка из списка, скажи об этом прямо («это твоя повторяющаяся история: ${card.leaks[0]?.label ?? "…"} — уже ${card.leaks[0]?.priorTotal ?? "N"} раз за последние дни») и разбирай строже: случайностью это уже не назвать. Если по списку виден прогресс — признай его одной короткой фразой, когда придётся к слову. Карточка — фон, а не тема разбора: не пересказывай её целиком, не приплетай без повода и не выдумывай числа и факты сверх приведённых.`;

  return selfLevelBlock ? `${memory}\n\n${selfLevelBlock}` : memory;
}

// Дата заметки в человеческом виде для тренера: «28.06» (год не нужен — заметки
// живут не дольше трёх месяцев, протухание в features/memory/coach-notes.ts).
function formatNoteDate(date: string): string {
  const m = /^\d{4}-(\d{2})-(\d{2})$/.exec(date);
  return m ? `${m[2]}.${m[1]}` : date;
}

// Фаза 3 памяти: жёсткий блок при детерминированном совпадении ошибки текущей раздачи
// с системным ликом карточки. Это не рекомендация, а обязанность: совпадение уже
// посчитал код по меткам парсера, тренеру остаётся только сказать об этом игроку.
export function renderRepeatedLeak(leak: PlayerCardLeak | null | undefined): string {
  if (!leak) return "";
  return `СОВПАДЕНИЕ НАШЁЛ ПАРСЕР (не догадка): решение в ЭТОЙ раздаче — то же самое, что системная ошибка игрока из карточки: ${leak.label} — уже ${leak.priorTotal} раз за ${leak.daysWithLeak} из ${leak.windowDays} последних игровых дней, и вот снова. Ты ОБЯЗАН сказать об этом игроку прямо, одной-двумя фразами: назови ошибку и число повторов («это уже ${leak.priorTotal + 1}-й раз за последние дни») и дай понять, что это паттерн, а не случайность. Других чисел не выдумывай.`;
}
