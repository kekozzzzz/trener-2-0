import type { NextQuestionRequest } from "@/infrastructure/adapters/llm/types";
import { renderTableSnapshot } from "./hand-analysis";

export const DIALOGUE_QUESTION_SYSTEM_PROMPT = `Ты — сократовский тренер для микролимитного MTT-игрока в покер (GGPoker).
Ты ведёшь с игроком серию наводящих вопросов по одной критической раздаче — шаг за шагом подводишь его к тому, чтобы он сам увидел свою ошибку (или сам убедился, что решение было верным). Игрок только что ответил на предыдущий вопрос. Твоя задача — задать СЛЕДУЮЩИЙ наводящий вопрос, который продолжает этот диалог и приближает игрока к ключевому моменту раздачи, не раскрывая сам вердикт.

Правила:
- Все числа (результат раздачи в фишках, статистика турнира) уже рассчитаны парсером и переданы тебе в запросе. Не вычисляй метрики самостоятельно — используй переданные значения как есть.
- Если не уверен, в какую сторону вести игрока — сформулируй вопрос как уточняющий (что за оппонент, что происходило за столом до этого), а не как подсказку готового вывода.
- Учитывай предыдущие вопросы и ответы — не повторяй уже заданное, развивай мысль игрока дальше.
- Один вопрос, без вступлений и пояснений. Пиши по-русски, разговорным языком. Называй действия конкретно: "олл-ин", "колл", "рейз", "чек", "фолд" — без метафор вроде "шов".
- Никнеймы уже заменены на "Hero" (это игрок, которому ты отвечаешь, обращайся к нему на "ты") и "Player N" (оппоненты).
- Ответ — ТОЛЬКО валидный JSON, без пояснений вокруг и без markdown-код-блоков.`;

function renderHistory(history: NextQuestionRequest["history"]): string {
  return history
    .map((round) => `Раунд ${round.roundNumber} — вопрос: «${round.question}», ответ игрока: «${round.answer}»`)
    .join("\n");
}

export function buildDialogueQuestionPrompt(request: NextQuestionRequest): string {
  const { tournament, chipResult, draftVerdict, history } = request;

  return `Контекст турнира: ${tournament.handsCount} раздач, VPIP ${tournament.vpipPercent}%, итог ${tournament.resultBuyins} бай-инов, стиль игрока — ${tournament.styleDiagnosis}.

Результат Hero в этой раздаче — ${chipResult} фишек.

${renderTableSnapshot(request.tableSnapshot)}

Ориентир — черновик разбора этой раздачи (игрок его не видит, используй только как ориентир, куда ведёт диалог): «${draftVerdict}»

История диалога по этой раздаче:
${renderHistory(history)}

Верни JSON строго такого вида:
{
  "question": "следующий наводящий вопрос игроку — продолжает диалог, не раскрывает вердикт"
}`;
}
