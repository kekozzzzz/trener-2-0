import type { NextQuestionRequest } from "@/infrastructure/adapters/llm/types";
import { COACH_FRAMEWORK, renderTableSnapshot } from "./hand-analysis";

export const DIALOGUE_QUESTION_SYSTEM_PROMPT = `Ты — сократовский тренер по покеру для игрока микролимитных турниров (MTT) на GGPoker. Ты ведёшь с игроком серию наводящих вопросов по одной критической раздаче — шаг за шагом подводишь его к тому, чтобы он сам увидел свою ошибку (или сам убедился, что решение было верным). Игрок только что ответил на предыдущий вопрос. Твоя задача — задать СЛЕДУЮЩИЙ наводящий вопрос, который продолжает диалог и приближает игрока к ключевому моменту раздачи, не раскрывая сам вердикт.

${COACH_FRAMEWORK}

## Как вести диалог

- Опирайся на фреймворк выше: следующий вопрос рождается из того принципа, который игрок ещё не увидел (главный вопрос раздачи, тип оппонента, чья доска, что он хотел добрать или выбить).
- Учитывай предыдущие вопросы и ответы — не повторяй уже заданное, развивай мысль игрока дальше.
- Один вопрос, без вступлений и пояснений. Не раскрывай вердикт — вопрос ведёт к выводу, а не выдаёт его.

Ответ — ТОЛЬКО валидный JSON, без текста вокруг и без markdown-код-блоков.`;

function renderHistory(history: NextQuestionRequest["history"]): string {
  return history
    .map((round) => `Раунд ${round.roundNumber} — вопрос: «${round.question}», ответ игрока: «${round.answer}»`)
    .join("\n");
}

export function buildDialogueQuestionPrompt(request: NextQuestionRequest): string {
  const { tournament, chipResult, draftVerdict, history } = request;

  return `Контекст турнира: ${tournament.handsCount} раздач, VPIP ${tournament.vpipPercent}%, итог ${tournament.resultBuyins} бай-инов, стиль игрока — ${tournament.styleDiagnosis}.

Результат Hero в этой раздаче — ${chipResult} фишек.

${renderTableSnapshot(request.tableSnapshot)}

Ориентир — черновик разбора этой раздачи (игрок его не видит, используй только как ориентир, куда ведёт диалог): «${draftVerdict}»

История диалога по этой раздаче:
${renderHistory(history)}

Верни JSON строго такого вида:
{
  "question": "следующий наводящий вопрос игроку — продолжает диалог, не раскрывает вердикт"
}`;
}
