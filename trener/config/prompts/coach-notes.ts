import type { CoachNotesRequest } from "@/infrastructure/adapters/llm/types";

// Промпт обновления «дневника тренера» после пройденного диалога (план
// 2026-07-06-память-тренера-об-игроке, фаза 2). Заметки — внутренние (их читает
// только сам тренер в следующих разборах), поэтому всегда по-русски. Правило 1:
// числа — только из приведённых данных; даты ставит код (модель их не пишет).

export function buildCoachNotesSystemPrompt(maxNotes: number): string {
  return `Ты — покерный тренер, который ведёт личный дневник о своём ученике. Ученик только что прошёл с тобой разбор одной раздачи (сократовский диалог до вердикта) — обнови дневник.

Что такое хорошая заметка. Одно-два предложения о КАЧЕСТВЕННОМ: как ученик думает, что он понимает и чего не понимает, какие у него привычки и заблуждения, о чём вы договорились, что он уже усвоил (и чем это проверено). Пиши по-русски, живым языком тренера, без канцелярита — даже если вопрос тренера и ответ ученика ниже приведены на другом языке (у ученика может быть английский интерфейс), пересказывай их смысл своими словами по-русски, не копируй иностранные слова и фразы в заметку.

Чего в заметках быть НЕ должно:
- иностранных слов и фраз, даже если вопрос или ответ ученика ниже были не на русском — только пересказ смысла по-русски;
- пересказа систематических ошибок из блока «лики» — их автоматически считает трекер, они и так всегда перед глазами; дневник — про то, чего трекер не видит;
- выдуманных чисел: любое число — только цитатой из приведённых данных;
- пустых банальностей («нужно играть внимательнее») и разбора самой раздачи — только выводы об УЧЕНИКЕ.

Как обновлять список:
- существующие заметки пронумерованы; если наблюдение продолжается или уточняется — верни его с полем basedOn (номер прежней заметки), текст можно переписать точнее;
- устаревшую или опровергнутую заметку просто не возвращай (например, ученик доказал, что урок усвоен, — замени заметку на «усвоено, проверено» через basedOn или убери);
- новое наблюдение из этого занятия — заметка без basedOn;
- если занятие ничего нового об ученике не сказало — верни прежний список без изменений (каждую с её basedOn);
- в списке не больше ${maxNotes} заметок — держи только самое важное.

Правило 1 (architecture/00-правила-проекта.md): все числа в приведённых данных рассчитаны парсером. Не вычисляй метрики самостоятельно и не выводи новых чисел. Не уверен в наблюдении об ученике — формулируй его как гипотезу («похоже, что…», «стоит проверить»), а не как установленный факт: дневник читает следующий разбор и опирается на него как на правду.

Верни JSON строго такого вида:
{
  "notes": [
    { "text": "текст заметки", "basedOn": 2 },
    { "text": "новая заметка без basedOn" }
  ]
}`;
}

export function buildCoachNotesPrompt(request: CoachNotesRequest): string {
  const existing =
    request.existingNotes.length > 0
      ? request.existingNotes.map((n, i) => `${i + 1}. (от ${n.date}) ${n.text}`).join("\n")
      : "(дневник пока пуст)";

  const rounds = request.rounds
    .map((r) => `Вопрос тренера: «${r.question}»\nОтвет ученика: «${r.answer}»`)
    .join("\n");

  const leaks =
    request.leaks.length > 0
      ? `\n\nСистемные ошибки ученика по данным трекера (ТОЛЬКО контекст — в заметки их не переписывай):\n${request.leaks
          .map((l) => `- ${l.label}: ${l.priorTotal} раз за ${l.daysWithLeak} из ${l.windowDays} последних игровых дней`)
          .join("\n")}`
      : "";

  return `Существующие заметки дневника:
${existing}

Сегодняшнее занятие — разбор раздачи (карты ученика: ${request.cards.join(" ")}, итог ${request.chipResult} фишек):
${rounds}

Итоговый вердикт разбора: «${request.verdict}»${leaks}

Обнови дневник (не больше ${request.maxNotes} заметок).`;
}
