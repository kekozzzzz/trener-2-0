// Формат турнира по названию из заголовка HH. Факты-v2, фаза 5: нокаут/баунти-флаг —
// общий факт для тренера. В нокаутах за выбивание соперника дают награду (баунти):
// колл-диапазоны шире обычного (охота за головами), короткий стек — мишень, а когда ты
// покрываешь идущего олл-ин короткого, награда за его голову субсидирует твой колл.
//
// Раньше этот сигнал жил только припиской в чарте рестила — тренер по общей раздаче
// «нокаут-фактора в данных не видел». Правило 1/3: признак считает код по названию,
// не LLM. Названия GG/PS/WMX: «Bounty Hunters», «Mystery Bounty», «GGMasters KO», «PKO».
const BOUNTY_MARKERS = /bounty|knockout|hunters|mystery|\bpko\b|\bko\b|нокаут|баунти/i;

export function isBountyTournament(name: string | null | undefined): boolean {
  return !!name && BOUNTY_MARKERS.test(name);
}
