import path from "path";

// Конфигурация автопостинга в канал. Значения — только здесь и в .env (правило №3).
//
// Каталог очереди постов на СЕРВЕРЕ (вне git): хранит queue.json (состояние постов:
// что, когда, одобрено ли) и файлы картинок. Живёт на проде, поэтому переживает
// выключение компьютера Артёма — планировщик и очередь работают на VM, не на его ПК.
// В деве/тестах по умолчанию — локальный каталог в рабочей папке.
export function getPostQueueDir(): string {
  return process.env.POST_QUEUE_DIR ?? path.join(process.cwd(), ".post-queue");
}
